#!/usr/bin/env python3
"""
Route data extractor for Syntheseus MCTS route pickle files.

MCTS routes are stored as MolSetNode objects rather than explicit molecule and
reaction nodes. Each state node contains a set of molecules in `node.mols`.
This extractor preserves that state structure and exports the molecules inside
each state.
"""

from __future__ import annotations

import json
import pickle
from datetime import date, datetime
from typing import Any


def _json_safe(value: Any) -> Any:
    """Convert common non-JSON objects to JSON-safe values."""
    if value is None or isinstance(value, (bool, int, float, str)):
        return value
    if isinstance(value, (datetime, date)):
        return value.isoformat()
    if isinstance(value, dict):
        return {str(k): _json_safe(v) for k, v in value.items()}
    if isinstance(value, (list, tuple, set, frozenset)):
        return [_json_safe(item) for item in value]
    return str(value)


def _molecule_info(mol: Any) -> dict[str, Any]:
    """Extract JSON-safe fields from a Syntheseus Molecule object."""
    metadata = dict(getattr(mol, "metadata", {}) or {})
    metadata.pop("rdkit_mol", None)

    return {
        "smiles": getattr(mol, "smiles", None),
        "identifier": getattr(mol, "identifier", None),
        "is_purchasable": bool(metadata.get("is_purchasable", False)),
        "metadata": _json_safe(metadata),
    }


def _state_node_info(node: Any) -> dict[str, Any]:
    """Extract JSON-safe fields from an MCTS MolSetNode."""
    mols = sorted(
        (_molecule_info(mol) for mol in getattr(node, "mols", [])),
        key=lambda mol_info: str(mol_info.get("smiles", "")),
    )
    purchasable_mols = [
        mol_info for mol_info in mols if bool(mol_info.get("is_purchasable", False))
    ]

    return {
        "depth": getattr(node, "depth", None),
        "node_type": type(node).__name__,
        "is_state": True,
        "is_mol": False,
        "mol_smiles": None,
        "is_rxn": False,
        "rxn_smiles": None,
        "rxn_class": None,
        "rxn_name": None,
        "is_purchasable": None,
        "has_solution": getattr(node, "has_solution", None),
        "is_expanded": getattr(node, "is_expanded", None),
        "num_visit": getattr(node, "num_visit", None),
        "creation_time": _json_safe(getattr(node, "creation_time", None)),
        "data": _json_safe(getattr(node, "data", {})),
        "mols": mols,
        "n_mols": len(mols),
        "purchasable_mol_smiles": [
            mol_info["smiles"]
            for mol_info in purchasable_mols
            if mol_info.get("smiles") is not None
        ],
        "n_purchasable_mols": len(purchasable_mols),
    }


def _mol_smiles_set(node_info: dict[str, Any]) -> set[str]:
    """Return the set of molecule SMILES stored in an extracted state node."""
    return {
        str(mol_info["smiles"])
        for mol_info in node_info.get("mols", [])
        if isinstance(mol_info, dict) and mol_info.get("smiles") is not None
    }


def _add_inferred_transition_info(route_data: dict[str, Any]) -> None:
    """
    Add inferred per-transition reactant information to MCTS state nodes.

    MCTS pickles store state nodes, not explicit reactions. For each consecutive
    state transition, newly introduced molecules are inferred as the reactants
    generated by that retrosynthetic step.
    """
    previous_node_info: dict[str, Any] | None = None

    for node_info in route_data.values():
        if previous_node_info is None:
            node_info["inferred_reactant_smiles"] = []
            node_info["inferred_reactant_count"] = 0
            node_info["inferred_expanded_mol_smiles"] = []
            previous_node_info = node_info
            continue

        previous_mols = _mol_smiles_set(previous_node_info)
        current_mols = _mol_smiles_set(node_info)
        inferred_reactants = sorted(current_mols - previous_mols)
        inferred_expanded = sorted(previous_mols - current_mols)

        node_info["inferred_reactant_smiles"] = inferred_reactants
        node_info["inferred_reactant_count"] = len(inferred_reactants)
        node_info["inferred_expanded_mol_smiles"] = inferred_expanded
        previous_node_info = node_info


def extract_mcts_data(file_path: str) -> str:
    """
    Extract MCTS state-node data from a pickled route.

    Args:
        file_path: Path to an MCTS route pickle file.

    Returns:
        JSON string keyed by node index in depth order.
    """
    with open(file_path, "rb") as f:
        route = pickle.load(f)

    sorted_nodes = sorted(
        enumerate(route),
        key=lambda item: (getattr(item[1], "depth", 0), item[0]),
    )

    route_data: dict[str, Any] = {}
    for idx, (_, node) in enumerate(sorted_nodes):
        route_data[f"node_{idx + 1}"] = _state_node_info(node)

    _add_inferred_transition_info(route_data)
    return json.dumps(route_data)


if __name__ == "__main__":
    import sys

    pickle_file = sys.argv[1]
    print(extract_mcts_data(pickle_file))
